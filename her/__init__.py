# her/ — the companion layer over Zero.
#
# Her gets to know you (intake), is already there when you look (presence),
# and reaches the devices you paired (devices, bridge). It has no brain of
# its own and no executor of its own: every ask from a Her surface goes
# through namespace/command/inbox like any other, and every fact Her keeps is
# a line in namespace/memory you can read or strike out yourself.
#
# The one rule that makes Her low-fallibility: Her never claims to know
# something about you that you did not say. Cite or abstain.
